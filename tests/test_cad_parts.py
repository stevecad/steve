import hashlib
import io
import tempfile
import time
import unittest
import zipfile
from pathlib import Path
from unittest.mock import patch
from fastapi.testclient import TestClient
from fastapi import HTTPException
from steve_desktop.cad_server import LocalCadServer
from steve_desktop.cad_parts import unpack_step, fetch_bytes


class PartsTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.server = LocalCadServer(self.temp.name)
        self.client = TestClient(self.server.app, headers={'x-steve-session': self.server.token})

    def tearDown(self):
        self.client.close()
        self.server.close()
        self.temp.cleanup()

    def test_mcmaster_zip_identity_reuse_and_restart(self):
        # Tiny valid STEP fixture generated by the same kernel used by the product.
        from steve_desktop.cad_service import CadProject
        from steve_desktop.cad_document import bracket
        project = CadProject.create(Path(self.temp.name)/'fixture')
        result = project.build(bracket())
        data = Path(project.export('STEP', result['revision'])['path']).read_bytes()
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, 'w') as archive:
            archive.writestr('../../91251A540_Socket Head Screw.STEP', data)
        response = self.client.post('/v1/vendor-parts/mcmaster', files={'file': ('91251A540.zip', buf.getvalue())})
        self.assertIn(response.status_code, (201, 202), response.text)
        body = response.json()
        deadline = time.monotonic()+30
        while body['status']=='validating' and time.monotonic()<deadline:
            time.sleep(.1)
            body = self.client.get('/v1/imports/'+body['id']).json()
        self.assertEqual(body['status'],'ready',body)
        reused = self.client.post('/v1/vendor-parts/mcmaster/91251a540/use').json()
        self.assertEqual(reused['id'],body['id'])
        self.assertEqual(reused['solids'],result['solids'])
        self.assertEqual(reused['mcmaster']['title'],'Socket Head Screw')
        self.assertEqual(len(self.client.get('/v1/vendor-parts/mcmaster?search=socket+91251').json()['parts']),1)
        self.assertEqual(self.client.get('/v1/vendor-parts/mcmaster?search=absent').json()['parts'],[])
        other = LocalCadServer(self.temp.name)
        try:
            self.assertEqual(other.parts.mcmaster_get('91251A540')['sha256'],hashlib.sha256(data).hexdigest())
        finally:
            other.close()
        self.assertEqual(body['filename'],'91251A540_Socket Head Screw.STEP')

    def test_standard_checksum_and_offline_reuse(self):
        data=b'ISO-10303-21;\nEND-ISO-10303-21;'
        sha=hashlib.sha256(data).hexdigest()
        item={'id':'bearing-608','name':'608 bearing','sha256':sha,'stepUrl':'https://raw.githubusercontent.com/test/a.step'}
        with patch('steve_desktop.cad_parts.catalog.part',return_value=item), patch('steve_desktop.cad_parts.fetch_bytes',return_value=b'ISO-10303-21;wrong'):
            response=self.client.post('/v1/standard-parts/bearing-608/import')
            self.assertEqual(response.status_code,422)
            self.assertNotIn(sha,self.server.state.get('imports',{}))
        # Catalog fetch is forbidden in this second call: a pinned local copy suffices.
        self.server.state['standard_parts']={'bearing-608':item}
        self.server.state['imports']={sha:{'id':sha,'sha256':sha,'status':'ready'}}
        (Path(self.temp.name)/'imports'/(sha+'.step')).write_bytes(data)
        with patch('steve_desktop.cad_parts.catalog.part',side_effect=AssertionError('network')),patch('steve_desktop.cad_parts.fetch_bytes',side_effect=AssertionError('network')):
            response=self.client.post('/v1/standard-parts/bearing-608/import')
        self.assertEqual(response.status_code,201)
        self.assertIn(sha,response.json()['standard_part']['provenance'])

    def test_malformed_uploads_and_untrusted_downloads(self):
        response=self.client.post('/v1/vendor-parts/mcmaster',files={'file':('91251A540.step',b'not step')})
        self.assertEqual(response.status_code,415)
        response=self.client.post('/v1/vendor-parts/mcmaster',files={'file':('91251A540.zip',b'not zip')})
        self.assertEqual(response.status_code,422)
        for url in ('http://127.0.0.1/a','https://raw.githubusercontent.com.evil/a','https://raw.githubusercontent.com:123/a','file:///a'):
            with self.assertRaises(HTTPException):fetch_bytes(url,{'raw.githubusercontent.com'},100)
        archive=io.BytesIO()
        with zipfile.ZipFile(archive,'w') as z:z.writestr('wrong.txt','hello')
        with self.assertRaises(HTTPException):unpack_step('a.zip',archive.getvalue())

if __name__=='__main__':unittest.main()
